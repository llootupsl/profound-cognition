#!/usr/bin/env bash
# ============================================================================
# 脚本名称: demo-record.sh
# 用途: 录制 profound-cognition 的 demo 执行过程，按 DAG 拓扑序生成 timeline.log
# 作者: 阿洋
# 版本: 5.1.0
# 日期: 2026-06-17
# 跨平台说明: 本脚本为 bash 版本（macOS/Linux）。Windows 用户请使用 demo-visualize.py
# ============================================================================
set -euo pipefail

# ----------------------------------------------------------------------------
# 变量定义
# ----------------------------------------------------------------------------
DEMO_PROMPT="穷尽分析中国新能源汽车产业的竞争格局与供应链韧性"
TIMELINE_LOG="assets/timeline.log"
OUTPUT_DIR="output/demo-$(date +%Y%m%d-%H%M%S)"

# ----------------------------------------------------------------------------
# 创建输出目录
# ----------------------------------------------------------------------------
mkdir -p "$OUTPUT_DIR"
mkdir -p "$(dirname "$TIMELINE_LOG")"

# ----------------------------------------------------------------------------
# 初始化 timeline.log，写入头部信息
# ----------------------------------------------------------------------------
{
  echo "============================================================"
  echo "Profound Cognition Demo Timeline"
  echo "============================================================"
  echo "Timestamp : $(date '+%Y-%m-%d %H:%M:%S')"
  echo "Version   : 5.1.0"
  echo "Prompt    : ${DEMO_PROMPT}"
  echo "Output Dir: ${OUTPUT_DIR}"
  echo "============================================================"
  echo ""
} > "$TIMELINE_LOG"

# ----------------------------------------------------------------------------
# record_step() 函数
#   参数 1: step_name        (如 T_env_probe)
#   参数 2: step_description (中文描述)
#   参数 3: status           (STARTED / COMPLETED)
# ----------------------------------------------------------------------------
record_step() {
  local step_name="$1"
  local step_description="$2"
  local status="$3"
  local ts
  ts="$(date '+%Y-%m-%d %H:%M:%S.%3N')"
  echo "[${ts}] [${status}] ${step_name} — ${step_description}" >> "$TIMELINE_LOG"
}

# ----------------------------------------------------------------------------
# 节点计数器
# ----------------------------------------------------------------------------
NODE_COUNT=0
GATE_COUNT=0
HARD_GATE_COUNT=0

# 辅助函数：录制一个节点（STARTED + COMPLETED）
record_node() {
  local name="$1"
  local desc="$2"
  record_step "$name" "$desc" "STARTED"
  sleep 0.1
  record_step "$name" "$desc" "COMPLETED"
  NODE_COUNT=$((NODE_COUNT + 1))
  sleep 0.1
}

# 辅助函数：录制 Gate 节点
record_gate() {
  local name="$1"
  local desc="$2"
  record_node "$name" "$desc"
  GATE_COUNT=$((GATE_COUNT + 1))
}

# 辅助函数：录制硬门控节点
record_hard_gate() {
  local name="$1"
  local desc="$2"
  record_node "$name" "$desc"
  HARD_GATE_COUNT=$((HARD_GATE_COUNT + 1))
}

# ============================================================================
# Demo 流程：按 DAG 拓扑序录制关键节点
# ============================================================================

# --- 阶段 0：环境探测与时间锚定 ----------------------------------------------
record_node "T_env_probe"        "环境探测：检测 EXHAUST 模式与 Token 配额"
record_node "T00a"               "时间锚定：固化研究时间戳与上下文窗口"

# --- 阶段 1：输入分流与声音校准 ----------------------------------------------
record_node "T01"                "输入分流：识别产品类型 research_report"
record_node "T01b"               "声音校准：锁定 NRSF 叙事基调"

# --- 阶段 2：研究大纲 --------------------------------------------------------
record_node "T00"                "研究大纲：生成 14 维全息框架骨架"

# --- 阶段 3：九层研究底座 T02-T06 -------------------------------------------
record_node "T02"                "研究底座 L1：领域边界与术语本体"
record_node "T03"                "研究底座 L2：历史脉络与演化路径"
record_node "T04"                "研究底座 L3：现状全景与关键玩家"
record_node "T05"                "研究底座 L4：结构拆解与价值链"
record_node "T06"                "研究底座 L5-L9：动力学/对比/趋势/风险/政策"

# --- 阶段 4：Gate-α ---------------------------------------------------------
record_gate "T07"                "Gate-α：研究底座完整性门控"

# --- 阶段 5：认知解构 + 多路径推理 -------------------------------------------
record_node "T08"                "认知解构：将研究目标分解为子问题树"
record_node "T09"                "多路径推理：生成 ≥3 条独立推理链"

# --- 阶段 6：三路对抗（并行模拟）---------------------------------------------
# T10 / T11 / T12 并行
(
  record_step "T10" "红队对抗：攻击推理链薄弱点" "STARTED"
  sleep 0.1
  record_step "T10" "红队对抗：攻击推理链薄弱点" "COMPLETED"
) &
(
  record_step "T11" "蓝队对抗：防御并加固论点" "STARTED"
  sleep 0.1
  record_step "T11" "蓝队对抗：防御并加固论点" "COMPLETED"
) &
(
  record_step "T12" "紫队对抗：综合裁决与融合" "STARTED"
  sleep 0.1
  record_step "T12" "紫队对抗：综合裁决与融合" "COMPLETED"
) &
wait
NODE_COUNT=$((NODE_COUNT + 3))
sleep 0.1

record_node "T12b"               "三路对抗交叉融合：生成统一对抗结论"

# --- 阶段 7：认知综合 --------------------------------------------------------
record_node "T13"                "认知综合：汇聚多路径推理与对抗结论"

# --- 阶段 8：迭代深化 --------------------------------------------------------
record_node "I01"                "迭代深化：Do-Check-Retry 循环"

# --- 阶段 9：Gate-β ---------------------------------------------------------
record_gate "T14"                "Gate-β：认知深度门控"

# --- 阶段 10：领域引擎 -------------------------------------------------------
record_node "T15"                "领域引擎：注入领域专属知识图谱"

# --- 阶段 11：Gate-γ --------------------------------------------------------
record_gate "T16"                "Gate-γ：领域适配门控"

# --- 阶段 12：事实核查 + 偏见检测（并行模拟）---------------------------------
(
  record_step "T17" "事实核查：交叉验证关键论据" "STARTED"
  sleep 0.1
  record_step "T17" "事实核查：交叉验证关键论据" "COMPLETED"
) &
(
  record_step "T18" "偏见检测：识别认知与数据偏差" "STARTED"
  sleep 0.1
  record_step "T18" "偏见检测：识别认知与数据偏差" "COMPLETED"
) &
wait
NODE_COUNT=$((NODE_COUNT + 2))
sleep 0.1

# --- 阶段 13：交付守卫 -------------------------------------------------------
record_node "T19"                "交付守卫：交付前最终自检"

# --- 阶段 14：全息框架 14 维 T22-T27 ----------------------------------------
record_node "T22"                "全息框架 D1-D2：时间维度 + 空间维度"
record_node "T23"                "全息框架 D3-D4：结构维度 + 功能维度"
record_node "T24"                "全息框架 D5-D6：主体维度 + 利益维度"
record_node "T25"                "全息框架 D7-D8：风险维度 + 机会维度"
record_node "T26"                "全息框架 D9-D11：技术/经济/社会维度"
record_node "T27"                "全息框架 D12-D14：生态/伦理/元维度"

# --- 阶段 15：Gate-终 -------------------------------------------------------
record_gate "T28"                "Gate-终：全息完整性终审门控"

# --- 阶段 16：科学层 7 模块 TM01-TM07 ---------------------------------------
record_node "TM01"               "科学层 M1：系统动力学建模"
record_node "TM02"               "科学层 M2：因果验证（DoWhy/反事实）"
record_node "TM03"               "科学层 M3：多智能体对抗仿真"
record_node "TM04"               "科学层 M4：情景规划（4 类未来）"
record_node "TM05"               "科学层 M5：元认知监控"
record_node "TM06"               "科学层 M6：覆盖验证（Gap Analysis）"
record_node "TM07"               "科学层 M7：本体导出（OWL/RDF）"

# --- 阶段 17：哲学核心 + 元维度 ---------------------------------------------
record_node "T_philosophical_core" "哲学三元组：本体论/认识论/方法论"
record_node "T_meta_dim_9_10"      "元维度 9-10：元认知 + 元伦理"
record_node "T_meta_dim_11_12"     "元维度 11-12：元学习 + 元演化"
record_node "T_meta_dim_13_14"     "元维度 13-14：元设计 + 元反思"

# --- 阶段 18：Gate-δ --------------------------------------------------------
record_gate "T_gate_delta"       "Gate-δ：哲学与元维度门控"

# --- 阶段 19：渲染 ----------------------------------------------------------
record_node "T20a"               "渲染：Markdown 长文渲染与图表嵌入"

# --- 阶段 20：输出卫士 ------------------------------------------------------
record_node "T20_output_guard"   "输出卫士：格式/长度/引用合规校验"

# --- 阶段 21：交付前硬门控 G1-G6 --------------------------------------------
record_hard_gate "G1"            "硬门控 G1：字数下限校验（≥10万字）"
record_hard_gate "G2"            "硬门控 G2：14 维覆盖完整性校验"
record_hard_gate "G3"            "硬门控 G3：科学层 7 模块落地校验"
record_hard_gate "G4"            "硬门控 G4：哲学三元组存在性校验"
record_hard_gate "G5"            "硬门控 G5：引用与事实可溯源校验"
record_hard_gate "G6"            "硬门控 G6：EXHAUST 穷尽性终审校验"

# ============================================================================
# 输出汇总信息
# ============================================================================
{
  echo ""
  echo "============================================================"
  echo "Demo 录制完成"
  echo "============================================================"
  echo "Timeline Log 路径 : ${TIMELINE_LOG}"
  echo "总节点数          : ${NODE_COUNT}"
  echo "总 Gate 数        : ${GATE_COUNT}"
  echo "硬门控数          : ${HARD_GATE_COUNT}"
  echo "============================================================"
} >> "$TIMELINE_LOG"

# 控制台输出
echo "============================================================"
echo "Demo 录制完成"
echo "============================================================"
echo "Timeline Log 路径 : ${TIMELINE_LOG}"
echo "总节点数          : ${NODE_COUNT}"
echo "总 Gate 数        : ${GATE_COUNT}"
echo "硬门控数          : ${HARD_GATE_COUNT}"
echo "============================================================"

exit 0
